"""Simple JSON modality used by tests, examples, and plugin plumbing demos."""

import copy
import json
import typing

import pydantic

import spec2gds.agent_spec.plugins.base as plugin
import spec2gds.agent_spec.package.archive as container


class SpecMetadataItem(pydantic.BaseModel):
    """
    Validation schema for an individual key-value item of spec metadata.
    Enforces basic types and required fields for structured hardware specs.
    """
    name: str = pydantic.Field(..., min_length=1, description="Alphanumeric identifier for the metadata item")
    value: typing.Union[int, str, bool] = pydantic.Field(..., description="Value associated with the key")
    description: typing.Optional[str] = pydantic.Field(None, description="Optional doc description")

class SimpleJSONSpecSchema(pydantic.BaseModel):
    """
    Top-level Pydantic validation schema for the SimpleJSON modality.
    Ensures that any JSON payload injected into our hybrid agent-spec archive 
    conforms to a strict template to prevent specs corruption.
    """
    title: str = pydantic.Field(..., min_length=1, description="Hardware component or block title")
    version: str = pydantic.Field(..., min_length=1, description="Specification revision version")
    metadata: list[SpecMetadataItem] = pydantic.Field(default_factory=list, description="List of metadata items")

class SimpleJSONPlugin:
    """
    Concrete Simple JSON modality plugin implementing the abstract ModalityPlugin protocol.
    Provides strict Pydantic validation, serialization, and JSON path resolution.
    """
    # Pre-declared config attribute (Mojo compatibility)
    config: plugin.ModalityPluginConfig

    def __init__(self) -> None:
        """Initialize the plugin configuration advertised to `PluginManager`."""
        self.config = plugin.ModalityPluginConfig(
            modality_id="simple-json",
            file_extensions=[".json"],
            media_type="application/x-spec-json"
        )

    def validate_data(self, data: typing.Any) -> bool:
        """
        Validate input payload strictly conforms to the JSON spec schema.
        
        Args:
            data: Payload dictionary to validate.
            
        Returns:
            True if data is valid, otherwise raises a validation exception.
        """
        if not isinstance(data, dict):
            raise TypeError("SimpleJSON data payload must be a dictionary.")

        # Run Pydantic validation. If data structure fails schema validation,
        # Pydantic raises a ValidationError which propagates to the caller.
        SimpleJSONSpecSchema(**data)
        return True

    def inject_data(
        self,
        container_instance: container.AgentSpecArchive,
        file_path: str,
        data: typing.Any
    ) -> None:
        """
        Inject validated JSON payload into the container and update manifest.
        
        Args:
            container_instance: AgentSpecArchive instance.
            file_path: Relative target file path (e.g. 'regs.json').
            data: Payload data dictionary.
        """
        # Keep command-line usage friendly by accepting both `regs` and
        # `regs.json`, but always store a concrete file extension.
        has_ext: bool = False
        for ext in self.config.file_extensions:
            if file_path.endswith(ext):
                has_ext = True
                break
        if not has_ext:
            file_path = file_path + self.config.file_extensions[0]

        # Validate before serialization so Pydantic errors point at the original
        # Python data rather than the generated byte stream.
        self.validate_data(data)

        # Use pretty JSON for archive inspectability. These payloads are meant
        # to be readable when someone unzips a `.spec` file.
        json_bytes: bytes = json.dumps(data, indent=2).encode("utf-8")
        
        # The modality id becomes the directory under `spec_data/`.
        full_path: str = f"spec_data/simple-json/{file_path}"
        container_instance.inject_file(full_path, json_bytes, self.config.media_type)

    def extract_data(
        self,
        container_instance: container.AgentSpecArchive,
        file_path: str
    ) -> typing.Any:
        """
        Extract JSON dict payload from the container.
        
        Args:
            container_instance: AgentSpecArchive instance.
            file_path: File name inside the spec_data/simple-json/ directory.
            
        Returns:
            Decoupled deep copy of the parsed JSON dictionary.
        """
        # Mirror `inject_data` path handling so callers can use either friendly
        # names or fully suffixed filenames on extraction.
        has_ext: bool = False
        for ext in self.config.file_extensions:
            if file_path.endswith(ext):
                has_ext = True
                break
        if not has_ext:
            file_path = file_path + self.config.file_extensions[0]

        full_path: str = f"spec_data/simple-json/{file_path}"
        
        # Read through the archive wrapper so callers get the cached/preserved
        # custom payload rather than poking at the ZIP directly.
        file_bytes: bytes = container_instance.extract_file(full_path)
        
        # Parse JSON bytes back into ordinary Python containers.
        parsed_dict: dict[str, typing.Any] = json.loads(file_bytes.decode("utf-8"))

        # Return a defensive copy so callers cannot mutate cached data.
        return copy.deepcopy(parsed_dict)

    def resolve_path(
        self,
        container_instance: container.AgentSpecArchive,
        file_path: str,
        node_path: str
    ) -> typing.Any:
        """
        Traverse the JSON payload hierarchy based on a slash-separated key path.
        
        Example:
            '/metadata/0/name' resolves to the 'name' attribute of the first metadata item.
            
        Args:
            container_instance: AgentSpecArchive instance.
            file_path: Target JSON file inside simple-json.
            node_path: Slash-separated traversal path.
            
        Returns:
            Decoupled deep copy of the resolved value (dict, list, or scalar).
        """
        # Work against the parsed data tree rather than string matching; this
        # keeps path resolution independent of JSON formatting.
        data_tree: typing.Any = self.extract_data(container_instance, file_path)
        
        # Clean path and handle root query
        clean_path: str = node_path.strip("/")
        if not clean_path:
            return copy.deepcopy(data_tree)

        parts: list[str] = clean_path.split("/")
        current_node: typing.Any = data_tree
        
        # Traverse hierarchy segment by segment. Dict segments are keys; list
        # segments must be integer indices.
        for part in parts:
            if isinstance(current_node, dict):
                # Dict key lookup
                if part in current_node:
                    current_node = current_node[part]
                else:
                    raise KeyError(f"Key '{part}' not found in JSON node.")
            elif isinstance(current_node, list):
                # List index lookup
                try:
                    idx: int = int(part)
                    current_node = current_node[idx]
                except ValueError:
                    raise KeyError(f"Cannot query list node with non-integer index: '{part}'")
                except IndexError:
                    raise IndexError(f"Index {idx} out of range for list node.")
            else:
                # Reached scalar leaf, cannot traverse further
                raise TypeError(f"Cannot traverse scalar value leaf node at path segment: '{part}'")

        # Return another copy because the resolved node may be a nested dict/list
        # from the parsed tree.
        return copy.deepcopy(current_node)
