"""Plugin domain models and manifest schemas for Verification Planner."""

from __future__ import annotations

from enum import Enum
from typing import Any, Literal
from pydantic import BaseModel, ConfigDict, Field

from testplan_service.constants import (
    MAX_TEXT_LENGTH,
    MAX_TITLE_LENGTH,
    SCHEMA_VERSION_GENERATION_REQUEST,
    SCHEMA_VERSION_GENERATION_RESULT,
)
from testplan_service.domain.objectives import CoverageObjective
from testplan_service.domain.recipes import BackendConfiguration, ProducerManifest, Recipe, TargetBindingSet


class PluginKind(str, Enum):
    """Classification of extension plugin."""

    BACKEND = "backend"
    RESULT_ADAPTER = "result_adapter"


class PluginPortability(str, Enum):
    """Portability declaration for plugin outputs."""

    PORTABLE = "portable"
    BACKEND_SPECIFIC = "backend_specific"


class PluginManifest(BaseModel):
    """Immutable manifest declaring plugin capabilities and configuration schema."""

    model_config = ConfigDict(extra="ignore")

    plugin_id: str
    version: str
    package_digest: str
    kind: PluginKind
    title: str = Field(min_length=1, max_length=MAX_TITLE_LENGTH)
    description: str = Field(default="", max_length=MAX_TEXT_LENGTH)
    contract_versions: list[str] = Field(default_factory=lambda: ["1.0"])
    input_schema_versions: list[str] = Field(default_factory=list)
    capabilities: dict[str, Any] = Field(default_factory=dict)
    configuration_schema: dict[str, Any] = Field(default_factory=dict)
    artifact_roles: list[str] = Field(default_factory=list)
    tool_requirements: dict[str, str] = Field(default_factory=dict)
    portability: PluginPortability = PluginPortability.PORTABLE
    enabled: bool = True
    diagnostic: str | None = None


class GenerationRequest(BaseModel):
    """Immutable input payload for backend generation."""

    model_config = ConfigDict(extra="ignore")

    schema_version: str = SCHEMA_VERSION_GENERATION_REQUEST
    checkpoint_id: str
    recipes: list[Recipe]
    target_binding_sets: list[TargetBindingSet]
    backend_configuration: BackendConfiguration
    coverage_objectives: list[CoverageObjective] = Field(default_factory=list)
    input_digest: str


class ArtifactDescriptor(BaseModel):
    """Metadata for an individual artifact generated by a backend."""

    model_config = ConfigDict(extra="ignore")

    relative_path: str
    role: str
    media_type: str = "text/plain"
    sha256: str
    size_bytes: int


class GenerationResult(BaseModel):
    """Outcome and staged artifact manifest produced by a backend plugin."""

    model_config = ConfigDict(extra="ignore")

    schema_version: str = SCHEMA_VERSION_GENERATION_RESULT
    input_digest: str
    plugin_id: str
    plugin_version: str
    plugin_digest: str
    artifacts: list[ArtifactDescriptor]
    producer_manifest: ProducerManifest
    source_map: list[dict[str, Any]] = Field(default_factory=list)
    realization_states: dict[str, str] = Field(default_factory=dict)
    diagnostics: list[dict[str, Any]] = Field(default_factory=list)
