/** Deterministic types from the supported contract subset. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
function type(node) {
  if (node.oneOf) return node.oneOf.map(type).join(' | ');
  if (Object.hasOwn(node, 'const')) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ');
  if (node.type === 'array') return `(${type(node.items ?? {})})[]`;
  if (node.type === 'object') {
    const required = new Set(node.required ?? []);
    const fields = Object.entries(node.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${type(value)};`).join(' ');
    return `{ ${fields}${node.additionalProperties === false ? '' : ' [key: string]: unknown;'} }`;
  }
  return { integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' }[node.type] ?? 'unknown';
}
const contracts = readdirSync(`${root}profile/catalog/tools`).sort().map(file => JSON.parse(readFileSync(`${root}profile/catalog/tools/${file}`, 'utf8')));
const text = '// Generated by scripts/generate-tool-arguments.mjs. Do not edit.\nexport interface ToolArguments {\n'
  + contracts.map(contract => `  ${JSON.stringify(contract.name)}: ${type(contract.input_schema)};`).join('\n')
  + '\n}\nexport type ToolName = keyof ToolArguments;\n';
const target = `${root}src/tool-arguments.ts`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) throw new Error('Generated tool arguments are stale. Run npm run generate:tools.');
} else writeFileSync(target, text);
